"""
tune_member3.py - Gain-tuning experiments for in-row guidance (Member 3)
CSAI4014 AISR Project

Runs the real controllers from controllers/agricultural_robot on a kinematic
in-row model (y' = v sin(psi), psi' = omega; e_y = y, e_psi = psi, positive = left)
for several start offsets / headings, sweeps gains, and writes:
  docs/member3_tuning_results.md
  docs/figures/m3_lateral_error.png
  docs/figures/m3_gain_sweep.png

Run (from repo root):   python scripts/tune_member3.py
"""

import itertools
import math
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "controllers", "agricultural_robot"))

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

from row_follower import MethodAPIDRowFollower, MethodBStanleyRowFollower

DT = 0.05
T_END = 20.0
SCENARIOS = [  # (name, y0 [m], psi0 [rad])
    ("offset +0.30 m", 0.30, 0.0),
    ("offset -0.30 m", -0.30, 0.0),
    ("heading +20 deg", 0.0, math.radians(20)),
    ("heading -20 deg", 0.0, math.radians(-20)),
    ("offset +0.25 m, heading -15 deg", 0.25, math.radians(-15)),
]


def simulate(follower, y0, psi0):
    follower.reset()
    y, psi, t = y0, psi0, 0.0
    ts, ys = [], []
    while t < T_END:
        v, omega = follower.compute(y, psi, DT)
        y += v * math.sin(psi) * DT
        psi += omega * DT
        t += DT
        ts.append(t)
        ys.append(y)
    return ts, ys


def metrics(ts, ys):
    n = len(ys)
    mae = sum(abs(e) for e in ys) / n
    rmse = math.sqrt(sum(e * e for e in ys) / n)
    max_dev = max(abs(e) for e in ys)
    settle = next((ts[i] for i in range(n)
                   if all(abs(e) < 0.02 for e in ys[i:])), float("nan"))
    return mae, rmse, max_dev, settle


def evaluate(make):
    rows = []
    for name, y0, psi0 in SCENARIOS:
        ts, ys = simulate(make(), y0, psi0)
        rows.append((name,) + metrics(ts, ys))
    avg = [sum(r[i] for r in rows) / len(rows) for i in range(1, 4)]
    return rows, avg


def main():
    os.makedirs(os.path.join(ROOT, "docs", "figures"), exist_ok=True)

    # ---- default gains (as committed in row_follower.py)
    res = {}
    res["Method A (PID) default"] = evaluate(lambda: MethodAPIDRowFollower())
    res["Method B (Stanley) default"] = evaluate(lambda: MethodBStanleyRowFollower())

    # ---- sweeps
    sweep_a = []
    for kp, kd in itertools.product([0.6, 1.0, 1.35, 1.8, 2.4], [0.0, 0.11, 0.22, 0.44]):
        _, avg = evaluate(lambda kp=kp, kd=kd: MethodAPIDRowFollower(kp_lat=kp, kd_lat=kd))
        sweep_a.append((kp, kd) + tuple(avg))
    sweep_b = []
    for ke in [0.5, 1.0, 1.7, 2.5, 3.5]:
        _, avg = evaluate(lambda ke=ke: MethodBStanleyRowFollower(stanley_gain=ke))
        sweep_b.append((ke,) + tuple(avg))

    best_a = min(sweep_a, key=lambda r: r[3])   # by RMSE
    best_b = min(sweep_b, key=lambda r: r[2])

    # ---- plots
    fig, axes = plt.subplots(1, 2, figsize=(11, 4), sharey=True)
    for ax, (label, make) in zip(axes, [
        ("Method A (PID)", lambda: MethodAPIDRowFollower()),
        ("Method B (Stanley)", lambda: MethodBStanleyRowFollower()),
    ]):
        for name, y0, psi0 in SCENARIOS:
            ts, ys = simulate(make(), y0, psi0)
            ax.plot(ts, [e * 100 for e in ys], label=name)
        ax.axhline(0, color="k", lw=0.6)
        ax.set_title(label)
        ax.set_xlabel("time (s)")
        ax.grid(alpha=0.3)
    axes[0].set_ylabel("lateral error e_y (cm)")
    axes[1].legend(fontsize=7)
    fig.tight_layout()
    fig.savefig(os.path.join(ROOT, "docs", "figures", "m3_lateral_error.png"), dpi=150)

    fig, ax = plt.subplots(1, 2, figsize=(11, 4))
    for kd in sorted({r[1] for r in sweep_a}):
        pts = [(r[0], r[3]) for r in sweep_a if r[1] == kd]
        ax[0].plot([p[0] for p in pts], [p[1] * 100 for p in pts], marker="o", label=f"Kd={kd}")
    ax[0].set_xlabel("Kp (lateral)"); ax[0].set_ylabel("mean RMSE (cm)")
    ax[0].set_title("Method A gain sweep"); ax[0].legend(); ax[0].grid(alpha=0.3)
    ax[1].plot([r[0] for r in sweep_b], [r[2] * 100 for r in sweep_b], marker="o")
    ax[1].set_xlabel("Stanley gain k_e"); ax[1].set_ylabel("mean RMSE (cm)")
    ax[1].set_title("Method B gain sweep"); ax[1].grid(alpha=0.3)
    fig.tight_layout()
    fig.savefig(os.path.join(ROOT, "docs", "figures", "m3_gain_sweep.png"), dpi=150)

    # ---- markdown report
    L = []
    L.append("# Member 3 - Row-Following Tuning Results\n")
    L.append("Generated by `scripts/tune_member3.py` using the real `row_follower.py` "
             "controllers on a kinematic in-row model "
             f"(dt = {DT} s, {T_END:.0f} s per run, 5 start scenarios).\n")
    L.append("## Default gains, per scenario\n")
    for label, (rows, avg) in res.items():
        L.append(f"### {label}\n")
        L.append("| Scenario | Mean abs e_y (cm) | RMSE (cm) | Max dev (cm) | Settle to 2 cm (s) |")
        L.append("|---|---|---|---|---|")
        for r in rows:
            L.append(f"| {r[0]} | {r[1]*100:.2f} | {r[2]*100:.2f} | {r[3]*100:.2f} | {r[4]:.2f} |")
        L.append(f"| **Average** | **{avg[0]*100:.2f}** | **{avg[1]*100:.2f}** | **{avg[2]*100:.2f}** | |\n")
    L.append("## Method A sweep (Kp_lat x Kd_lat), averaged over scenarios\n")
    L.append("| Kp_lat | Kd_lat | Mean abs e_y (cm) | RMSE (cm) | Max dev (cm) |")
    L.append("|---|---|---|---|---|")
    for r in sweep_a:
        L.append(f"| {r[0]} | {r[1]} | {r[2]*100:.2f} | {r[3]*100:.2f} | {r[4]*100:.2f} |")
    L.append(f"\nLowest RMSE in sweep: Kp_lat={best_a[0]}, Kd_lat={best_a[1]} "
             f"(RMSE {best_a[3]*100:.2f} cm).\n")
    L.append("## Method B sweep (Stanley gain k_e), averaged over scenarios\n")
    L.append("| k_e | Mean abs e_y (cm) | RMSE (cm) | Max dev (cm) |")
    L.append("|---|---|---|---|")
    for r in sweep_b:
        L.append(f"| {r[0]} | {r[1]*100:.2f} | {r[2]*100:.2f} | {r[3]*100:.2f} |")
    L.append(f"\nLowest RMSE in sweep: k_e={best_b[0]} (RMSE {best_b[2]*100:.2f} cm).\n")
    L.append("## Figures\n")
    L.append("- `docs/figures/m3_lateral_error.png` - e_y vs time, both methods, all scenarios")
    L.append("- `docs/figures/m3_gain_sweep.png` - RMSE vs gains\n")
    L.append("## Note\n")
    L.append("These are kinematic-model results. Webots results (wheel slip, sensor noise, "
             "speed limits) will differ; run the world and add those numbers separately.\n")
    with open(os.path.join(ROOT, "docs", "member3_tuning_results.md"), "w") as f:
        f.write("\n".join(L))

    print("\n".join(L[:20]))
    print("\nWrote docs/member3_tuning_results.md and docs/figures/m3_*.png")


if __name__ == "__main__":
    main()
